-- Prefer the running client's generic control labels when available. Secret values
-- are never compared, formatted, or assigned to a FontString.
local function native(key, global)
  local value = _G[global]
  if issecretvalue and issecretvalue(value) then return end
  if type(value) == "string" and value ~= "" then L[key] = value end
end
native("search", "SEARCH")
native("all", "ALL")
native("back", "BACK")
